"""OS-FLASHDIET P3: pack the FX picker's names and descriptions (app/fx/fx_text.txt) into one blob.

    fx_text_pack.py --text app/fx/fx_text.txt --out <build>/gen/fx_text_blob.cpp

The authoring file holds one line per picker entry, in model/fx_table.h kPickerOrder order:

    <name><TAB><description>

The packer checks the line count against model::fx::kPickerCount (read from model/fx_table.h), printable
ASCII only, and the lengths the reader's buffers hold (kFxNameMax / kFxDescMax, read from
app/include/o3os/app/fx_text.h). The inflated text is the packed form the reader streams: every name, one
per line, then every description, one per line ('\\n' ends a line; the names come first so that the list's
rows, which need only names, decode a short prefix). It is deflated with tools/deflate_pack.py (the
deterministic encoder, never zlib) and emitted as o3os::app::kFxTextZ / kFxTextZSize / kFxTextRawSize
(declared in app/include/o3os/app/fx_text.h). Stdlib only.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import deflate_pack  # noqa: E402  (tools/deflate_pack.py, OS-FLASHDIET A2)

REPO = Path(__file__).resolve().parent.parent
FX_TEXT_H = REPO / "app/include/o3os/app/fx_text.h"
FX_TABLE_H = REPO / "model/include/o3os/model/fx_table.h"


def _header_const(path: Path, name: str) -> int:
    m = re.search(r"\b%s\s*=\s*(\d+)" % re.escape(name), path.read_text())
    if not m:
        raise SystemExit("fx_text_pack: %s has no %s" % (path, name))
    return int(m.group(1))


def parse(text: str, count: int, name_max: int, desc_max: int):
    """[(name, description), ...] of an fx_text.txt; raises ValueError on a bad line or a wrong count."""
    rows = text.split("\n")
    if rows and rows[-1] == "":
        rows.pop()  # the file's final newline
    out = []
    for lineno, raw in enumerate(rows, 1):
        parts = raw.split("\t")
        if len(parts) != 2:
            raise ValueError("line %d: want <name><TAB><description>" % lineno)
        name, desc = parts
        for what, s, cap in (("name", name, name_max), ("description", desc, desc_max)):
            if not s:
                raise ValueError("line %d: empty %s" % (lineno, what))
            if not all(0x20 <= ord(c) < 0x7F for c in s):
                raise ValueError("line %d: the %s is not printable ASCII" % (lineno, what))
            if len(s) > cap:
                raise ValueError("line %d: the %s is %d characters, the reader holds %d" % (lineno, what, len(s), cap))
        out.append((name, desc))
    if len(out) != count:
        raise ValueError("%d lines, model::fx::kPickerCount is %d" % (len(out), count))
    return out


def packed(rows) -> bytes:
    """The inflated text: the names, then the descriptions, one per line."""
    return ("".join(n + "\n" for n, _ in rows) + "".join(d + "\n" for _, d in rows)).encode("ascii")


def emit(raw: bytes, z: bytes) -> str:
    stream = deflate_pack.emit_cpp("FxTextStream", raw, z)
    return "\n".join([
        "// Generated by tools/fx_text_pack.py from app/fx/fx_text.txt -- do not edit.",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#include <o3os/app/fx_text.h>",
        "",
        stream,
        "namespace o3os::app {",
        "",
        "// The packed FX picker text, as declared in fx_text.h: the deflate stream of the %d raw bytes." % len(raw),
        "extern const std::uint8_t* const kFxTextZ = kFxTextStream.bytes;",
        "extern const std::size_t kFxTextZSize = kFxTextStreamZSize;",
        "extern const std::size_t kFxTextRawSize = kFxTextStreamRawSize;",
        "",
        "}  // namespace o3os::app",
        ""])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--text", type=Path, required=True, help="the authoring file (app/fx/fx_text.txt)")
    ap.add_argument("--out", type=Path, required=True, help="where to write the generated fx_text_blob.cpp")
    args = ap.parse_args(argv)
    try:
        rows = parse(args.text.read_text(), _header_const(FX_TABLE_H, "kPickerCount"),
                     _header_const(FX_TEXT_H, "kFxNameMax") - 1, _header_const(FX_TEXT_H, "kFxDescMax") - 1)
    except ValueError as e:
        print("fx_text_pack: %s: %s" % (args.text, e), file=sys.stderr)
        return 1
    raw = packed(rows)
    z = deflate_pack.deflate(raw)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(emit(raw, z))
    return 0


if __name__ == "__main__":
    sys.exit(main())
