"""OS-FLASHDIET P4: pack the custom play orders' entry table into one deflate blob.

    play_orders_pack.py --data seq/src/play_orders_data.inc --out <build>/gen/play_orders_blob.cpp

seq/src/play_orders_data.inc (committed; tools/gen_play_orders.py writes it) holds `kEntries[N]`, N std::uint16_t. The packer reads those numbers
back, lays them out as the table sits in memory on the little-endian MK66 (low byte first), deflates the bytes with tools/deflate_pack.py (the
deterministic encoder, never zlib) and emits o3os::seq::kPlayOrdersZ / kPlayOrdersZSize / kPlayOrdersRawSize (declared in
seq/include/o3os/seq/play_orders.h). The firmware inflates it once at boot into an SDRAM table. The data stays the approved MIT component of
THIRD_PARTY.md; the blob is only its packed form. Stdlib only.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import deflate_pack  # noqa: E402  (tools/deflate_pack.py, OS-FLASHDIET A2)


def entries(text: str):
    """The numbers of `kEntries[N] = { ... };` in play_orders_data.inc; raises ValueError when the table is malformed."""
    m = re.search(r"kEntries\[(\d+)\]\s*=\s*\{([^}]*)\}", text)
    if not m:
        raise ValueError("no kEntries table")
    count = int(m.group(1))
    values = [int(v, 16) for v in re.findall(r"0[xX]([0-9A-Fa-f]+)", m.group(2))]
    if len(values) != count:
        raise ValueError("kEntries[%d] holds %d numbers" % (count, len(values)))
    if any(v > 0xFFFF for v in values):
        raise ValueError("a number does not fit a std::uint16_t")
    return values


def table_bytes(values) -> bytes:
    """The table's bytes as the little-endian target holds them."""
    return b"".join(v.to_bytes(2, "little") for v in values)


def emit(raw: bytes, z: bytes) -> str:
    stream = deflate_pack.emit_cpp("PlayOrdersStream", raw, z)
    return "\n".join([
        "// Generated by tools/play_orders_pack.py from seq/src/play_orders_data.inc -- do not edit.",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#include <o3os/seq/play_orders.h>",
        "",
        stream,
        "namespace o3os::seq {",
        "",
        "// The packed play-order entries, as declared in play_orders.h: the deflate stream of the %d raw bytes (%d std::uint16_t)." % (len(raw), len(raw) // 2),
        "extern const std::uint8_t* const kPlayOrdersZ = kPlayOrdersStream.bytes;",
        "extern const std::size_t kPlayOrdersZSize = kPlayOrdersStreamZSize;",
        "extern const std::size_t kPlayOrdersRawSize = kPlayOrdersStreamRawSize;",
        "",
        "}  // namespace o3os::seq",
        ""])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", type=Path, required=True, help="the committed table (seq/src/play_orders_data.inc)")
    ap.add_argument("--out", type=Path, required=True, help="where to write the generated play_orders_blob.cpp")
    args = ap.parse_args(argv)
    try:
        values = entries(args.data.read_text())
    except ValueError as e:
        print("play_orders_pack: %s: %s" % (args.data, e), file=sys.stderr)
        return 1
    raw = table_bytes(values)
    z = deflate_pack.deflate(raw)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(emit(raw, z))
    return 0


if __name__ == "__main__":
    sys.exit(main())
