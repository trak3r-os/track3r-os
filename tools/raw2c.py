"""Turns a binary file into a C++ byte array, for embedding a built artifact in a target test (OS-FLASHDIET I2: the packed tracker.tmod
into the QEMU suite that imports through it).

  raw2c.py --name <symbol> --out <file.cpp> <input>

emits `namespace { alignas(4) const std::uint8_t k_<symbol>[] = {...}; const unsigned k_<symbol>_size = N; }`. Stdlib only.
"""
import argparse
import sys


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("input")
    args = ap.parse_args(argv[1:])
    data = open(args.input, "rb").read()
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/raw2c.py from %s: do not edit." % args.input,
        "#include <cstdint>",
        "",
        "extern const std::uint8_t k_%s[];" % args.name,
        "extern const unsigned k_%s_size;" % args.name,
        "alignas(4) const std::uint8_t k_%s[] = {" % args.name,
    ]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines += [
        "};",
        "const unsigned k_%s_size = %du;" % (args.name, len(data)),
        "",
    ]
    open(args.out, "w").write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
