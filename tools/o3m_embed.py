"""Turns .tmod files into the C++ table of the built-in modules (OS-012d, module/include/o3os/module/builtin.h; OS-FLASHDIET A3, P1: compressed).

    o3m_embed.py --out <file.cpp> --notice <file>... [<stem>=<file.tmod>...]

Each file's 64-byte header goes into a const array raw (builtin_header() and prefers_card() read it in place) and the rest of the file is deflated by
tools/deflate_pack.py -- our own deterministic raw-deflate encoder, never Python's zlib (its output changes with the zlib library, and the reproducible-image
gate must not depend on the build machine's) -- into a word-aligned stream (deflate_pack's emit_cpp); the table lists the header pointer, the stream (z, z_size)
and the whole file's size. The loader reads the header from `data` and inflates the rest with its own core::Inflater, so the CRC and every check run on the
inflated bytes exactly as they do on a card's file. The notice files are joined into one text, deflated the same way (kBuiltinNotices, OS-FLASHDIET P1: the licence text the modules'
code requires the image to carry; the console streams it with module::notices_page()). Nothing is parsed or changed. Stdlib only.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I takes the script's directory off sys.path: import deflate_pack from beside this file
import deflate_pack

kHeader = 64  # sizeof(o3m_file_header): the part of the file that stays raw


def notice_text(text: bytes) -> bytes:
    """The bytes the image carries: the joined notices with LF line ends and one more LF (what the string literal of earlier images ended with)."""
    return text.decode("utf-8").replace("\r\n", "\n").encode("utf-8") + b"\n"


def generate(modules, notices) -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/o3m_embed.py from the built .tmod files (OS-012d; OS-FLASHDIET A3: each file's 64-byte header raw, the rest",
        "// deflated by tools/deflate_pack.py). Do not edit.",
        "#include <o3os/module/builtin.h>",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
    ]
    for stem, data in modules:
        header, rest = data[:kHeader], data[kHeader:]
        z = deflate_pack.deflate(rest)
        body = deflate_pack.emit_cpp(stem, rest, z)
        body = body[body.index("namespace {"):]  # emit_cpp's includes and banner are per file; generate() emits them once above
        lines.append(f"// {stem}.tmod: {len(data)} bytes = the {kHeader}-byte header raw + {len(rest)} bytes deflated to {len(z)}")
        lines.append(f"namespace z_{stem} {{")
        lines.append(body.rstrip("\n"))
        lines.append("}  // namespace z_%s" % stem)
        lines.append("")
    text = notice_text(notices)
    z = deflate_pack.deflate(text)
    body = deflate_pack.emit_cpp("notices", text, z)
    body = body[body.index("namespace {"):]
    lines.append(f"// The licence notices: {len(text)} bytes of text deflated to {len(z)} (module/builtin.h: BuiltinNotices, notices_page)")
    lines.append("namespace z_notices {")
    lines.append(body.rstrip("\n"))
    lines.append("}  // namespace z_notices")
    lines.append("")
    lines += [
        "namespace o3os::module {",
        "namespace {",
    ]
    for stem, data in modules:
        header = data[:kHeader]
        lines.append(f"alignas(4) const std::uint8_t k_{stem}_h[{kHeader}] = {{  // {stem}.tmod's header, raw")
        for i in range(0, kHeader, 24):
            lines.append("    " + ",".join(str(b) for b in header[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const BuiltinModule kBuiltinModules[] = {")
    for stem, data in modules:
        lines.append('    {"%s", k_%s_h, z_%s::k%s.bytes, static_cast<std::uint32_t>(z_%s::k%sZSize), %du},'
                     % (stem, stem, stem, stem, stem, stem, len(data)))
    if not modules:
        lines.append("    {nullptr, nullptr, nullptr, 0u, 0u},  // no .tmod was built (no cross compiler): the count says 0")
    lines.append("};")
    lines.append(f"const unsigned kBuiltinModuleCount = {len(modules)};")
    lines.append("")
    lines.append("const BuiltinNotices kBuiltinNotices = {z_notices::knotices.bytes, static_cast<std::uint32_t>(z_notices::knoticesZSize), %du};" % len(text))
    lines.append("}  // namespace o3os::module")
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--notice", action="append", default=[])
    ap.add_argument("modules", nargs="*", help="<stem>=<file.tmod>")
    args = ap.parse_args(argv)
    mods = []
    for spec in args.modules:
        stem, _, path = spec.partition("=")
        if not re.fullmatch(r"[A-Za-z0-9_]{1,31}", stem) or not path:
            print(f"o3m_embed: bad module spec '{spec}' (stem=file, stem of letters, digits and _)", file=sys.stderr)
            return 2
        with open(path, "rb") as f:
            data = f.read()
        if len(data) < kHeader or len(data) % 4 != 0:
            print(f"o3m_embed: {path} is not a .tmod file (size {len(data)})", file=sys.stderr)
            return 2
        mods.append((stem, data))
    notices = b""
    for path in args.notice:
        with open(path, "rb") as f:
            notices += f.read().rstrip() + b"\n\n"
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(generate(mods, notices.rstrip() + b"\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
