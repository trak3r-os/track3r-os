"""OS-FLASHDIET P6: pack the built-in key bindings table into one deflate blob.

    bindings_pack.py --bin <build>/gen/builtin_bindings.bin --out <build>/gen/builtin_bindings_blob.cpp

app/CMakeLists.txt compiles app/src/bindings.cpp a second time with O3OS_BINDINGS_DUMP into an object library (the same compiler, flags and ABI as the
firmware, so the host build holds the host's layout and the MK66 build the target's), and `objcopy -O binary --only-section=.rodata.o3_builtin_bindings`
lifts the constexpr table's bytes out of that object: --bin. This script deflates them with tools/deflate_pack.py (the deterministic encoder, never
zlib) and emits o3os::app::kBuiltinBindingsZ / kBuiltinBindingsZSize / kBuiltinBindingsRawSize (declared in app/include/o3os/app/bindings.h). The
firmware inflates the blob once at boot into an SDRAM table. Stdlib only.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import deflate_pack  # noqa: E402  (tools/deflate_pack.py, OS-FLASHDIET A2)

BINDING_SIZE = 16  # sizeof(core::Binding), static_assert in core/binding.h


def emit(raw: bytes, z: bytes) -> str:
    stream = deflate_pack.emit_cpp("BuiltinBindingsStream", raw, z)
    return "\n".join([
        "// Generated by tools/bindings_pack.py from the built-in bindings table (app/src/bindings.cpp) -- do not edit.",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#include <o3os/app/bindings.h>",
        "",
        stream,
        "namespace o3os::app {",
        "",
        "// The packed built-in bindings, as declared in bindings.h: the deflate stream of the %d raw bytes (%d bindings of %d bytes)." % (len(raw), len(raw) // BINDING_SIZE, BINDING_SIZE),
        "extern const std::uint8_t* const kBuiltinBindingsZ = kBuiltinBindingsStream.bytes;",
        "extern const std::size_t kBuiltinBindingsZSize = kBuiltinBindingsStreamZSize;",
        "extern const std::size_t kBuiltinBindingsRawSize = kBuiltinBindingsStreamRawSize;",
        "",
        "}  // namespace o3os::app",
        ""])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bin", type=Path, required=True, help="the table's bytes (objcopy -O binary of the dump object's section)")
    ap.add_argument("--out", type=Path, required=True, help="where to write the generated builtin_bindings_blob.cpp")
    args = ap.parse_args(argv)
    raw = args.bin.read_bytes()
    if not raw or len(raw) % BINDING_SIZE != 0:
        print("bindings_pack: %s: %d bytes, not a whole number of %d-byte bindings" % (args.bin, len(raw), BINDING_SIZE), file=sys.stderr)
        return 1
    z = deflate_pack.deflate(raw)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(emit(raw, z))
    return 0


if __name__ == "__main__":
    sys.exit(main())
