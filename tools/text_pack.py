"""OS-FLASHDIET P5/P8: pack a platform text file (platform/mk66/text/*.txt) into one deflate blob and its id header.

    text_pack.py --text platform/mk66/text/console_text.txt --symbol ConsoleText --ns txt \
                 --ids <build>/gen/o3os/platform/mk66/console_text_ids.h --out <build>/gen/console_text_blob.cpp \
                 --expect <build>/gen/o3os/platform/mk66/console_text_expect.h
    text_pack.py --self-test

The authoring file holds one string per line:

    <key><TAB><text as a C string literal body>

`#` starts a comment line, empty lines are skipped. The text uses exactly the escapes \\n \\t \\\\ \\" \\' (anything else is an
error) and printable ASCII otherwise; it is the very text the C++ source had as a literal, so the served bytes are the
old ones. The inflated blob is every text followed by its NUL, in file order; a string's id is the byte offset of its
first character, so a lookup is one addition. The ids header declares one `inline constexpr std::uint16_t <key>` per
string in namespace o3os::platform::mk66::<ns> and the blob's raw size; the blob source defines
o3os::platform::mk66::k<Symbol>Z / k<Symbol>ZSize (declared in text.h). Deflated with tools/deflate_pack.py (the
deterministic encoder, never zlib). Stdlib only.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import deflate_pack  # noqa: E402  (tools/deflate_pack.py, OS-FLASHDIET A2)

ESC = {"n": "\n", "t": "\t", "\\": "\\", '"': '"', "'": "'"}
KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def unescape(s: str) -> str:
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\":
            if i + 1 >= len(s) or s[i + 1] not in ESC:
                raise ValueError("bad escape in %r" % s)
            out.append(ESC[s[i + 1]])
            i += 2
        else:
            if not 0x20 <= ord(c) < 0x7F:
                raise ValueError("not printable ASCII: %r" % s)
            out.append(c)
            i += 1
    return "".join(out)


def parse(text: str):
    """[(key, text), ...] of a text file; raises ValueError on a bad line or a repeated key."""
    rows = []
    seen = set()
    for lineno, raw in enumerate(text.split("\n"), 1):
        if raw == "" or raw.startswith("#"):
            continue
        parts = raw.split("\t", 1)
        if len(parts) != 2 or not KEY.match(parts[0]) or parts[1] == "":
            raise ValueError("line %d: want <key><TAB><text>" % lineno)
        if parts[0] in seen:
            raise ValueError("line %d: key %s repeated" % (lineno, parts[0]))
        seen.add(parts[0])
        try:
            rows.append((parts[0], unescape(parts[1])))
        except ValueError as e:
            raise ValueError("line %d: %s" % (lineno, e))
    if not rows:
        raise ValueError("no strings")
    return rows


def layout(rows):
    """(raw blob bytes, [(key, offset)]): every text then its NUL."""
    raw = bytearray()
    offs = []
    for key, s in rows:
        offs.append((key, len(raw)))
        raw += s.encode("ascii") + b"\0"
    if len(raw) > 0xFFFF:
        raise ValueError("%d bytes do not fit a 16-bit id" % len(raw))
    return bytes(raw), offs


def emit_ids(offs, raw_size: int, ns: str, src: str) -> str:
    out = ["// Generated by tools/text_pack.py from %s -- do not edit." % src,
           "// SPDX-License-Identifier: GPL-3.0-or-later",
           "#pragma once",
           "",
           "#include <cstddef>",
           "#include <cstdint>",
           "",
           "namespace o3os::platform::mk66::%s {" % ns,
           "",
           "inline constexpr std::size_t kRawSize = %d;  // the inflated blob: every text and its NUL" % raw_size,
           ""]
    for key, off in offs:
        out.append("inline constexpr std::uint16_t %s = %d;" % (key, off))
    out += ["", "}  // namespace o3os::platform::mk66::%s" % ns, ""]
    return "\n".join(out)


def emit_blob(symbol: str, raw: bytes, z: bytes, src: str) -> str:
    stream = deflate_pack.emit_cpp(symbol + "Stream", raw, z)
    return "\n".join([
        "// Generated by tools/text_pack.py from %s -- do not edit." % src,
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#include <o3os/platform/mk66/text.h>",
        "",
        stream,
        "namespace o3os::platform::mk66 {",
        "",
        "// The packed text, as declared in text.h: the deflate stream of the %d raw bytes." % len(raw),
        "extern const std::uint8_t* const k%sZ = k%sStream.bytes;" % (symbol, symbol),
        "extern const std::size_t k%sZSize = k%sStreamZSize;" % (symbol, symbol),
        "static_assert(k%sStreamRawSize == %d, \"text_pack: the raw size\");" % (symbol, len(raw)),
        "",
        "}  // namespace o3os::platform::mk66",
        ""])


def emit_expect(rows, offs, ns: str, src: str) -> str:
    """The test-only table of every text as the C literal the authoring file spells (the test compares the served text with it)."""
    out = ["// Generated by tools/text_pack.py from %s -- do not edit (tests only)." % src,
           "// SPDX-License-Identifier: GPL-3.0-or-later",
           "#pragma once",
           "",
           "#include <cstdint>",
           "",
           "namespace o3os::platform::mk66::%s {" % ns,
           "",
           "struct Expect {",
           "  std::uint16_t id;",
           "  const char* text;",
           "};",
           "inline constexpr Expect kExpect[] = {"]
    for (key, off), (_, s) in zip(offs, rows):
        lit = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
        out.append('    {%d, "%s"},  // %s' % (off, lit, key))
    out += ["};", "", "}  // namespace o3os::platform::mk66::%s" % ns, ""]
    return "\n".join(out)


def self_test() -> int:
    assert unescape(r"a\n\t\\\"\'b") == "a\n\t\\\"'b"
    for bad in (r"\x", "tab\there", "caf\u00e9", "end\\"):
        try:
            unescape(bad)
        except ValueError:
            continue
        raise AssertionError("accepted %r" % bad)
    rows = parse("# c\n\nfoo\thello\\n\nbar_1\tx\n")
    assert rows == [("foo", "hello\n"), ("bar_1", "x")], rows
    raw, offs = layout(rows)
    assert raw == b"hello\n\0x\0" and offs == [("foo", 0), ("bar_1", 7)], (raw, offs)
    for bad in ("nokey", "1bad\tx", "k\t", "k\ta\nk\tb", "# only"):
        try:
            parse(bad)
        except ValueError:
            continue
        raise AssertionError("accepted %r" % bad)
    z = deflate_pack.deflate(raw)
    assert z and len(z) < 64
    assert "inline constexpr std::uint16_t bar_1 = 7;" in emit_ids(offs, len(raw), "txt", "t.txt")
    assert '{7, "x"},  // bar_1' in emit_expect(rows, offs, "txt", "t.txt")
    # every real text file of the tree parses, its keys are C identifiers and the ids fit
    for f in sorted((Path(__file__).resolve().parent.parent / "platform/mk66/text").glob("*_text.txt")):
        r, o = layout(parse(f.read_text()))
        assert len(r) <= 0xFFFF and o
    print("text_pack self-test ok")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--self-test", action="store_true", help="run the built-in checks and exit")
    ap.add_argument("--text", type=Path, help="the authoring file")
    ap.add_argument("--symbol", help="CamelCase symbol stem of the blob (ConsoleText)")
    ap.add_argument("--ns", help="namespace of the ids (txt)")
    ap.add_argument("--ids", type=Path, help="where to write the ids header")
    ap.add_argument("--out", type=Path, help="where to write the blob source")
    ap.add_argument("--expect", type=Path, help="where to write the test-only table of the literals")
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    if not (args.text and args.symbol and args.ns and args.ids and args.out and args.expect):
        ap.error("--text, --symbol, --ns, --ids, --out and --expect are required")
    try:
        rows = parse(args.text.read_text())
        raw, offs = layout(rows)
    except ValueError as e:
        print("text_pack: %s: %s" % (args.text, e), file=sys.stderr)
        return 1
    z = deflate_pack.deflate(raw)
    src = args.text.name
    for path, body in ((args.ids, emit_ids(offs, len(raw), args.ns, src)), (args.out, emit_blob(args.symbol, raw, z, src)),
                       (args.expect, emit_expect(rows, offs, args.ns, src))):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
