"""Build the starter-content zip of an alpha release (OS-STARTER; standard library only; run it with `python3 -I`).

  make_starter.py --version 0.6.7 --ptf path/to/track3r-os-0.6.7.ptf --modules-dir build-os-host/modules [--out build-release]

writes OUT/track3r-os-<version>.zip (and a .sha256 file and a licence-check record next to it). The zip is meant to be unpacked into the
root of the SD card. It holds:

  Firmware/<name>.ptf and .sha256   the update file given with --ptf
  modules/apps/*.tmod               the apps listed in the manifest, taken from --modules-dir (a build directory's modules/)
  modules/effects/*.tmod            the effect modules (track inserts) listed in the manifest
  modules/instruments/*.tmod        the instrument modules that are not inside the firmware (sine; TB-303, chip, FM and SID are built in)
  modules/presets/<id>/*.o3mp       the factory preset packs of the manifest's `presets` list (modules/<id>/presets.json)
  modules/importers/*.tmod          the importer modules listed in the manifest (tracker: MOD / S3M / MED import, OS-FLASHDIET I3)
  Effects/*.ptfx                    the Sample Editor plugins of the manifest's `ptfx` list, built from modules/ptfx and taken from --ptfx-dir (OS-PTFXPACK)
  Samples/, WTABLE/, Songs/         third-party files from starter_manifest.json, fetched, checked against their SHA-256, never stored in git
  Samples/Drums, WTABLE/Generated,  our own content, generated by tools/release/gen (deterministic, CC0)
  Songs/MED, Projects/Starter-*
  README.txt, LICENSES/, SHA256SUMS

Rules (they are checks, not wishes):
  - Every third-party file is in the manifest with URL, SHA-256, licence, author, title, source and target path. A download whose SHA-256 differs
    fails the run. The allowed licences are CC0-1.0, Public-Domain, CC-BY-4.0 and GPL-3.0; any other value in the manifest is refused.
  - A Mod Archive file (manifest field modarchive_id) has its licence re-read on the module's page before packing; a licence that is not the
    one in the manifest, or a page that cannot be read, fails the run.
  - The zip is reproducible: sorted entries, a fixed time stamp, fixed attributes, the same bytes for the same inputs.
  - A packed .ptfx file is read back through the 3.1 checks of tools/ptfx_inspect.py (it must be OK), and its source modules/ptfx/<name>/<name>.c must carry
    `SPDX-License-Identifier: MIT`. MIT is allowed for this `ptfx` section only (the plugins come from polyend/tracker-ce, which the maintainer approved
    component by component, CLAUDE.md hard rule 1); the licence text modules/ptfx/LICENSE-tracker-ce.txt goes to LICENSES/ and CREDITS.txt names the files.
  - Nothing is written inside the repository except below a build*/ directory (the default output is build-release/, untracked).

--offline never touches the network: files come from the cache (named by SHA-256) and the Mod Archive pages from the cache too. The ctest
`starter_python` uses it with fake files. Network access happens only when a person runs this script without --offline.
--check-manifest validates the manifest (licences, paths, fields) and exits; it needs neither a network nor a firmware file.
"""
