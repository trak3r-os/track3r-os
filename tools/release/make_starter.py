# The kind a packed module carries in its header (byte 8: magic, header size and target come first; module/sdk/o3module.h, tools/o3m_gen.py KINDS), per folder.
# The firmware looks for a file in the folder of its kind only (module/src/loader.cpp open_file; app/src/module_ui.cpp scan_*), so a module in the wrong folder is not found.
KIND_BYTE = 8
KIND_OF = {"instruments": 1, "effects": 2, "importers": 3, "apps": 4}


def collect_modules(manifest, modules_dir):
    out = {}
    folders = {"apps": "modules/apps/", "instruments": "modules/instruments/", "effects": "modules/effects/", "importers": "modules/importers/"}
    for kind in ("apps", "instruments", "effects", "importers"):
        for stem in manifest["modules"][kind]:
            path = os.path.join(modules_dir, stem + ".tmod")
            if not os.path.isfile(path):
                raise StarterError("module %s.tmod is not in %s (build the modules first)" % (stem, modules_dir))
            with open(path, "rb") as f:
                data = f.read()
            if data[:4] != b"O3MD" or len(data) <= KIND_BYTE:
                raise StarterError("%s is not a .tmod file (it does not start with O3MD)" % path)
            if data[KIND_BYTE] != KIND_OF[kind]:
                raise StarterError("%s has module kind %d but is listed under modules.%s (kind %d)" % (path, data[KIND_BYTE], kind, KIND_OF[kind]))
            out[folders[kind] + stem + ".tmod"] = data
    return out


def collect_presets(manifest, repo_root=None):
    """The factory preset packs (OS-MODPRESET P5): modules/<id>/presets.json of each id in the manifest's `presets` list, built by
    tools/o3preset.py into modules/presets/<id>/<name>.o3mp. StarterError when a pack is missing or refused."""
    root = repo_root or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    sys.path.insert(0, os.path.join(root, "tools"))
    try:
        import o3preset
    finally:
        sys.path.pop(0)
    out = {}
    for stem in manifest.get("presets", []):
        path = os.path.join(root, "modules", stem, "presets.json")
        if not os.path.isfile(path):
            raise StarterError("preset pack %s is missing" % path)
        try:
            for name, preset in o3preset.load_pack(path):
                out["modules/presets/%s/%s.o3mp" % (stem, name)] = o3preset.build(preset)
        except o3preset.PackError as exc:
            raise StarterError("preset pack %s: %s" % (stem, exc))
    return out


def _ptfx_inspect(root):
    sys.path.insert(0, os.path.join(root, "tools"))
    try:
        import ptfx_inspect
    finally:
        sys.path.pop(0)
    return ptfx_inspect


def collect_ptfx(manifest, ptfx_dir, repo_root=None):
    """The `ptfx` section (OS-PTFXPACK): ({Effects/<name>.ptfx: bytes}, [(name, display name, size)]). Each file is <ptfx_dir>/<name>.ptfx, built from
    modules/ptfx/<name>/<name>.c (the CMake target o3_ptfx or tools/ptfx_pack.py). It must pass the 3.1 checks of tools/ptfx_inspect.py, and its source must
    be MIT (the SPDX line in the first lines). StarterError for the first file that does not."""
    root = repo_root or ROOT
    out = {}
    info = []
    plugins = manifest.get("ptfx", [])
    if plugins and not ptfx_dir:
        raise StarterError("the manifest lists .ptfx plugins: give --ptfx-dir (the build directory's modules/ptfx; build the o3_ptfx target first)")
    insp = _ptfx_inspect(root) if plugins else None
    for stem in plugins:
        path = os.path.join(ptfx_dir, stem + ".ptfx")
        if not os.path.isfile(path):
            raise StarterError("plugin %s.ptfx is not in %s (build the o3_ptfx target first)" % (stem, ptfx_dir))
        src = os.path.join(root, "modules", "ptfx", stem, stem + ".c")
        try:
            with open(src, "r", encoding="utf-8") as f:
                head = [f.readline() for _ in range(3)]
        except OSError:
            raise StarterError("plugin %s: its source %s is missing" % (stem, src))
        if not any(line.strip() == "// SPDX-License-Identifier: " + PTFX_LICENCE for line in head):
            raise StarterError("plugin %s: its source %s does not say SPDX-License-Identifier: %s" % (stem, src, PTFX_LICENCE))
        # A stale build must not ship: the file has to be at least as new as its source, the SDK header and the packer (a release step builds o3_ptfx first, --ptfx-build).
        built = os.path.getmtime(path)
        for dep in (src, os.path.join(root, "modules", "ptfx", "sdk", "tracker_plugin.h"), os.path.join(root, "tools", "ptfx_pack.py")):
            if os.path.isfile(dep) and os.path.getmtime(dep) > built:
                raise StarterError("plugin %s.ptfx in %s is older than %s: it is stale (build the o3_ptfx target again, or pass --ptfx-build)" % (stem, ptfx_dir, os.path.relpath(dep, root)))
        with open(path, "rb") as f:
            data = f.read()
        header = insp.parse_header(data)
        if header["status"] != "Ok":
            raise StarterError("%s is refused by the .ptfx checks: %s" % (path, header["message"]))
        if not header["name"].strip():
            raise StarterError("%s has no display name" % path)
        out[PTFX_FOLDER + stem + ".ptfx"] = data
        info.append((stem, header["name"], len(data)))
    return out, info


def build_ptfx(build_dir):
    """Build the o3_ptfx target of the configured build directory (a release must not pack an old build). StarterError when cmake is missing or the build fails."""
    try:
        res = subprocess.run(["cmake", "--build", build_dir, "--target", "o3_ptfx"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    except OSError as e:
        raise StarterError("--ptfx-build: cannot run cmake: %s" % e)
    if res.returncode != 0:
        raise StarterError("--ptfx-build: building the o3_ptfx target in %s failed (exit %d):\n%s" % (build_dir, res.returncode, res.stdout[-2000:]))


def ptfx_licence_text(repo_root=None):
    path = os.path.join(repo_root or ROOT, PTFX_LICENCE_SRC)
    try:
        with open(path, "rb") as f:
            data = f.read()
    except OSError as e:
        raise StarterError("cannot read the licence text %s: %s" % (path, e))
    if b"MIT" not in data:
        raise StarterError("%s is not the MIT licence text" % path)
    return data


