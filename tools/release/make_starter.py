STEM_RE = r"[A-Za-z0-9_]{1,31}"


class StarterError(Exception):
    pass


def sha256_hex(data):
    return hashlib.sha256(data).hexdigest()


# ---- the manifest ---------------------------------------------------------------------------------------------------------

def load_manifest(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError) as e:
        raise StarterError("cannot read the manifest %s: %s" % (path, e))


def _check_dest(dest, where):
    if not isinstance(dest, str) or not dest or dest.startswith("/") or "\\" in dest or ":" in dest:
        raise StarterError("%s: bad target path %r" % (where, dest))
    if any(part in ("", ".", "..") for part in dest.split("/")):
        raise StarterError("%s: bad target path %r" % (where, dest))
    if not dest.startswith(DEST_ROOTS):
        raise StarterError("%s: target %r is outside %s" % (where, dest, ", ".join(DEST_ROOTS)))


def validate_manifest(m):
    """Raises StarterError for the first problem: an unknown licence, a missing field, a bad path or hash, a licence without its text."""
    if not isinstance(m, dict) or m.get("schema") != 1:
        raise StarterError("manifest: schema must be 1")
    files = m.get("files")
    texts = m.get("licence_texts")
    if not isinstance(files, list) or not isinstance(texts, list):
        raise StarterError("manifest: 'files' and 'licence_texts' must be lists")
    seen = set()
    text_for = set()
    for kind, entries in (("licence_texts", texts), ("files", files)):
        for i, e in enumerate(entries):
            where = "manifest %s[%d]" % (kind, i)
            if not isinstance(e, dict):
                raise StarterError(where + ": not an object")
            need = ("dest", "url", "sha256", "licence") if kind == "licence_texts" else REQUIRED
            for key in need:
                if not isinstance(e.get(key), str) or not e[key].strip():
                    raise StarterError("%s: missing or empty %r" % (where, key))
            where = "%s (%s)" % (where, e["dest"])
            _check_dest(e["dest"], where)
            if e["dest"] in seen:
                raise StarterError(where + ": the target path is used twice")
            seen.add(e["dest"])
            if e["licence"] not in ALLOWED_LICENCES:
                raise StarterError("%s: licence %r is not allowed (allowed: %s)" % (where, e["licence"], ", ".join(ALLOWED_LICENCES)))
            if not re.fullmatch(r"[0-9a-f]{64}", e["sha256"]):
                raise StarterError(where + ": sha256 must be 64 lowercase hex digits")
            if not e["url"].startswith("https://"):
                raise StarterError(where + ": the URL must be https")
            if kind == "licence_texts":
                if not e["dest"].startswith("LICENSES/"):
                    raise StarterError(where + ": a licence text goes to LICENSES/")
                text_for.add(e["licence"])
            else:
                if e["dest"].startswith("LICENSES/"):
                    raise StarterError(where + ": a content file cannot go to LICENSES/")
                if "modarchive_id" in e:
                    if not isinstance(e["modarchive_id"], int) or e["modarchive_id"] <= 0:
                        raise StarterError(where + ": bad modarchive_id")
                    if e["licence"] not in MODARCHIVE_LICENCE_URLS:
                        raise StarterError("%s: a Mod Archive file may be %s only" % (where, " or ".join(MODARCHIVE_LICENCE_URLS)))
    # CC-BY-4.0 and Public-Domain texts are generated; CC0 and GPL texts must be fetched (the full legal text ships with the files).
    for e in files:
        if e["licence"] in ("CC0-1.0", "GPL-3.0") and e["licence"] not in text_for:
            raise StarterError("manifest: %s is used by %s but has no entry in licence_texts" % (e["licence"], e["dest"]))
    mods = m.get("modules")
    if not isinstance(mods, dict) or not all(isinstance(mods.get(k), list) for k in ("apps", "instruments", "effects", "importers")):
        raise StarterError("manifest: 'modules' needs the lists apps, instruments, effects and importers")
    for k in ("apps", "instruments", "effects", "importers"):
        for stem in mods[k]:
            if not isinstance(stem, str) or not re.fullmatch(r"[A-Za-z0-9_]{1,31}", stem):
                raise StarterError("manifest: bad module name %r" % (stem,))
    packs = m.get("presets", [])
    if not isinstance(packs, list):
        raise StarterError("manifest: 'presets' must be a list of module ids")
    for stem in packs:
        if not isinstance(stem, str) or not re.fullmatch(r"[A-Za-z0-9_]{1,31}", stem):
            raise StarterError("manifest: bad preset pack module id %r" % (stem,))
    plugins = m.get("ptfx", [])
    if not isinstance(plugins, list):
        raise StarterError("manifest: 'ptfx' must be a list of plugin names (modules/ptfx/<name>/<name>.c)")
    for stem in plugins:
        if not isinstance(stem, str) or not re.fullmatch(STEM_RE, stem):
            raise StarterError("manifest: bad .ptfx plugin name %r" % (stem,))
    if len(set(plugins)) != len(plugins):
        raise StarterError("manifest: a .ptfx plugin is listed twice")


# ---- fetching -------------------------------------------------------------------------------------------------------------

def http_get(url, retries=3):
    last = None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except (urllib.error.URLError, OSError) as e:
            last = e
            time.sleep(1 + attempt)
    raise StarterError("cannot download %s: %s" % (url, last))


def fetch(entry, cache, offline):
    """The bytes of a manifest file: from the cache (named by SHA-256, checked again), else downloaded and checked. A mismatch fails the run."""
    want = entry["sha256"]
    path = os.path.join(cache, want)
    if os.path.isfile(path):
        with open(path, "rb") as f:
            data = f.read()
        if sha256_hex(data) == want:
            return data
        if offline:
            raise StarterError("cache file %s does not match its SHA-256 (delete it)" % path)
    if offline:
        raise StarterError("offline: %s (%s) is not in the cache %s" % (entry["dest"], want[:12], cache))
    data = http_get(entry["url"])
    got = sha256_hex(data)
    if got != want:
        raise StarterError("SHA-256 mismatch for %s\n  url:      %s\n  expected: %s\n  got:      %s" % (entry["dest"], entry["url"], want, got))
    os.makedirs(cache, exist_ok=True)
    tmp = path + ".part"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)
    return data


def modarchive_page_url(mid):
    return "https://modarchive.org/index.php?request=view_by_moduleid&query=%d" % mid


def read_modarchive_licence(html):
    """(link, text) of the 'Licensed under the <a href=...>text</a>' line of a Mod Archive module page, or None."""
    m = re.search(r'Licensed under the\s*<a[^>]*href="([^"]+)"[^>]*>([^<]*)</a>', html)
    return (m.group(1).strip(), m.group(2).strip()) if m else None


def _norm_url(url):
    url = re.sub(r"^http://", "https://", url.strip())
    return url if url.endswith("/") else url + "/"


def check_modarchive(entry, cache, offline):
    """Re-reads the licence on the module's Mod Archive page and fails when it is not the manifest's. Returns the record line."""
    mid = entry["modarchive_id"]
    page_cache = os.path.join(cache, "modarchive-%d.html" % mid)
    if offline:
        if not os.path.isfile(page_cache):
            raise StarterError("offline: the Mod Archive page of module %d is not in the cache (%s)" % (mid, page_cache))
        with open(page_cache, "rb") as f:
            raw = f.read()
    else:
        try:
            raw = http_get(modarchive_page_url(mid))
        except StarterError as e:
            raise StarterError("cannot read the licence of Mod Archive module %d (%s): %s" % (mid, entry["dest"], e))
        os.makedirs(cache, exist_ok=True)
        with open(page_cache, "wb") as f:
            f.write(raw)
    found = read_modarchive_licence(raw.decode("utf-8", "replace"))
    if found is None:
        raise StarterError("cannot read the licence of Mod Archive module %d (%s): no 'Licensed under' line on the page, did the page change?" % (mid, entry["dest"]))
    want = MODARCHIVE_LICENCE_URLS[entry["licence"]]
    if _norm_url(found[0]) != _norm_url(want):
        raise StarterError("the licence of Mod Archive module %d changed\n  %s\n  manifest says %s (%s)\n  the page says   %s (%s)" %
                           (mid, entry["dest"], entry["licence"], want, found[1], found[0]))
    return "module %d  %s  page: %s (%s)  manifest: %s" % (mid, entry["dest"], found[1], found[0], entry["licence"])


