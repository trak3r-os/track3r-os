    for lic in ALLOWED_LICENCES:
        group = [e for e in files if e["licence"] == lic]
        if not group:
            continue
        lines += ["%s: %s" % (lic, LICENCE_NAMES[lic]), "-" * 60]
        by_source = {}
        for e in group:
            by_source.setdefault((e["author"], e["source"]), []).append(e)
        for (author, source), items in sorted(by_source.items()):
            lines.append("by %s" % author)
            lines.append("source: %s" % source)
            for e in sorted(items, key=lambda x: x["dest"]):
                lines.append("  %-44s %s" % (e["dest"], e["title"]))
            if lic == "CC-BY-4.0":
                lines.append("licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); the files are not modified")
            elif lic == "GPL-3.0":
                lines.append("Copyright the Surge Synth Team; GPL-3.0, the text is LICENSES/GPL-3.0.txt; these are data files, the file is its own source")
            lines.append("")
    return "\n".join(lines) + "\n"


