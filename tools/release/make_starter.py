def sums_text(entries):
    return "".join("%s  %s\n" % (sha256_hex(entries[p]), p) for p in sorted(entries))


def write_zip(path, entries):
    """Writes `entries` ({path: bytes}) as a reproducible zip: sorted, fixed time stamp and attributes, deflate level 9."""
    tmp = path + ".part"
    with zipfile.ZipFile(tmp, "w") as z:
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=ZIP_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            z.writestr(info, entries[name], compresslevel=9)
    os.replace(tmp, path)


def check_out_dir(out):
    """Nothing is written into the repository tree except below a build*/ directory (ignored by git)."""
    real = os.path.realpath(out)
    root = os.path.realpath(ROOT)
    if real == root or real.startswith(root + os.sep):
        first = os.path.relpath(real, root).split(os.sep)[0]
        if first == "." or not first.startswith("build"):
            raise StarterError("%s is inside the repository: use a directory outside it, or one below build*/" % out)


def check_version(version):
    if not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z._+-]{0,31}", version):
        raise StarterError("bad --version %r (letters, digits and . _ + - only)" % version)


def build_entries(manifest, version, ptf_path, modules_dir, cache, offline, ptfx_dir=None, repo_root=None):
    """The whole archive as ({path: bytes}, licence record lines)."""
    entries = {}
    record = []
    if not (os.path.isfile(ptf_path) and ptf_path.lower().endswith(".ptf")):
        raise StarterError("--ptf must be an existing .ptf file: %s" % ptf_path)
    with open(ptf_path, "rb") as f:
        ptf = f.read()
    if not ptf:
        raise StarterError("the .ptf file is empty")
    ptf_name = os.path.basename(ptf_path)
    entries["Firmware/" + ptf_name] = ptf
    entries["Firmware/" + ptf_name + ".sha256"] = ("%s  %s\n" % (sha256_hex(ptf), ptf_name)).encode()

    entries.update(collect_modules(manifest, modules_dir))
    entries.update(collect_presets(manifest))
    ptfx_files, ptfx_info = collect_ptfx(manifest, ptfx_dir, repo_root)
    entries.update(ptfx_files)
    if ptfx_files:
        entries[PTFX_LICENCE_TEXT] = ptfx_licence_text(repo_root)

    for e in manifest["files"]:
        if "modarchive_id" in e:
            record.append(check_modarchive(e, cache, offline))
        entries[e["dest"]] = fetch(e, cache, offline)
    for e in manifest["licence_texts"]:
        entries[e["dest"]] = fetch(e, cache, offline)

    generated = generate()
    clash = sorted(set(generated) & set(entries))
    if clash:
        raise StarterError("generated content and fetched content use the same path: " + ", ".join(clash))
    entries.update(generated)

    used = {e["licence"] for e in manifest["files"]}
    for dest, text in licence_texts_generated(used).items():
        if dest in entries:
            raise StarterError("LICENSES text %s is both fetched and generated" % dest)
        entries[dest] = text.encode("utf-8")
    entries["LICENSES/CREDITS.txt"] = credits_text(version, manifest["files"], generated, ptfx_info).encode("utf-8")
    entries["README.txt"] = readme_text(version, ptf_name, bool(ptfx_files)).encode("utf-8")
    entries["SHA256SUMS"] = sums_text(entries).encode("utf-8")
    return entries, record


def summary(entries):
    folders = {}
    for path, data in entries.items():
        top = path.split("/")[0] if "/" in path else "(root)"
        n, size = folders.get(top, (0, 0))
        folders[top] = (n + 1, size + len(data))
    lines = ["%-12s %4d files %10d bytes" % (top, n, size) for top, (n, size) in sorted(folders.items())]
    lines.append("%-12s %4d files %10d bytes" % ("total", len(entries), sum(len(d) for d in entries.values())))
    return lines


def run(argv):
    ap = argparse.ArgumentParser(description="Build the track3r-os starter-content zip (OS-STARTER).")
    ap.add_argument("--version", help="release version, used in the zip name")
    ap.add_argument("--ptf", help="the track3r-os .ptf update file to include (Firmware/)")
    ap.add_argument("--modules-dir", help="a build directory's modules/ folder with the .tmod files")
    ap.add_argument("--ptfx-dir", help="the build directory's modules/ptfx folder with the .ptfx files (needed when the manifest has a `ptfx` list)")
    ap.add_argument("--ptfx-build", help="a configured CMake build directory: its o3_ptfx target is built before the .ptfx files are packed (--ptfx-dir defaults to its modules/ptfx)")
    ap.add_argument("--out", default=os.path.join(ROOT, "build-release"), help="output directory (default: build-release/ in the repository, untracked)")
    ap.add_argument("--cache", help="download cache (default: OUT/cache)")
    ap.add_argument("--manifest", default=DEFAULT_MANIFEST, help="the manifest of third-party files")
    ap.add_argument("--offline", action="store_true", help="no network: use the cache only (tests)")
    ap.add_argument("--check-manifest", action="store_true", help="validate the manifest and exit")
    args = ap.parse_args(argv)

    manifest = load_manifest(args.manifest)
    validate_manifest(manifest)
    if args.check_manifest:
        mods = manifest["modules"]
        print("manifest ok: %d files, %d licence texts, %d apps, %d instruments, %d effects, %d importers, %d preset packs, %d .ptfx plugins" % (
            len(manifest["files"]), len(manifest["licence_texts"]), len(mods["apps"]), len(mods["instruments"]), len(mods["effects"]), len(mods["importers"]),
            len(manifest.get("presets", [])), len(manifest.get("ptfx", []))))
        return 0
    for need in ("version", "ptf", "modules_dir"):
        if not getattr(args, need):
            ap.error("--%s is required" % need.replace("_", "-"))
    check_version(args.version)
    if args.ptfx_build:
        built_dir = os.path.join(args.ptfx_build, "modules", "ptfx")
        if args.ptfx_dir and os.path.realpath(args.ptfx_dir) != os.path.realpath(built_dir):
            ap.error("--ptfx-dir %s is not the output folder of --ptfx-build (%s): the build would not be what is packed" % (args.ptfx_dir, built_dir))
        build_ptfx(args.ptfx_build)
        args.ptfx_dir = built_dir
    check_out_dir(args.out)
    cache = args.cache or os.path.join(args.out, "cache")
    os.makedirs(args.out, exist_ok=True)

    entries, record = build_entries(manifest, args.version, args.ptf, args.modules_dir, cache, args.offline, args.ptfx_dir)
    zip_path = os.path.join(args.out, "track3r-os-%s.zip" % args.version)
    write_zip(zip_path, entries)
    with open(zip_path, "rb") as f:
        digest = sha256_hex(f.read())
    with open(zip_path + ".sha256", "w", encoding="utf-8") as f:
        f.write("%s  %s\n" % (digest, os.path.basename(zip_path)))
    if record:
        with open(os.path.join(args.out, "track3r-os-%s.licence-check.txt" % args.version), "w", encoding="utf-8") as f:
            when = "read from the cache (offline)" if args.offline else "re-read " + datetime.date.today().isoformat()
            f.write("Mod Archive licences, %s\n" % when)
            f.write("\n".join(record) + "\n")
    print("\n".join(summary(entries)))
    print("wrote %s (%d bytes) sha256 %s" % (zip_path, os.path.getsize(zip_path), digest))
    return 0


def main(argv):
    try:
        return run(argv)
    except StarterError as e:
        print("make_starter: " + str(e), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
