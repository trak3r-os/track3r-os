def generate():
    """{zip path: bytes}: everything of ours (tools/release/gen), CC0. Deterministic."""
    sys.path.insert(0, GEN_DIR)
    try:
        import drumkit
        import med_song
        import projects
        import wavetables
    finally:
        sys.path.remove(GEN_DIR)
    kit = drumkit.files()
    tables = wavetables.files()
    out = {}
    for name, data in kit.items():
        out["Samples/Drums/" + name] = data
