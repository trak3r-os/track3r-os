constexpr std::size_t kChunks[] = {1, 7, 64, 4096};

const inflate_fixtures::Good* find_good(const char* name) {
  for (std::size_t i = 0; i < inflate_fixtures::kGoodCount; ++i) {
    if (std::strcmp(inflate_fixtures::kGood[i].name, name) == 0) {
      return &inflate_fixtures::kGood[i];
    }
  }
  return nullptr;
}

